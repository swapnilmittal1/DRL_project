"""Render the EDA markdown report from analysis_summary.json.

Every number and every directional statement below is computed from the summary, so the report
cannot drift from the data it describes.
"""

from __future__ import annotations

FIG = "../figures/eda"
BUCKETS = ("low", "medium", "high")


def _pct(x: float, nd: int = 1) -> str:
    return f"{100 * x:.{nd}f}%"


def _trend(values: list[float]) -> str:
    if all(b > a for a, b in zip(values, values[1:])):
        return "increases monotonically"
    if all(b < a for a, b in zip(values, values[1:])):
        return "decreases monotonically"
    return "is non-monotonic"


def _rho(d: dict) -> str:
    p = "p < 1e-300" if d["p_value"] == 0 else f"p = {d['p_value']:.1e}"
    return f"ρ = {d['rho']:.3f} ({p}, n = {d['n']:,})"


def _strength(r: float) -> str:
    a = abs(r)
    return "negligible" if a < 0.1 else "weak" if a < 0.3 else "moderate" if a < 0.5 else "strong"


def render_report(s: dict) -> str:
    c, sp, th, cf = s["counts"], s["splits"], s["thresholds"], s["confounders"]
    bb = cf["by_bucket"]
    m_all, ratings, tl, mod = s["margin"]["all_kept"], s["ratings"], s["token_lengths"], s["models"]
    t1, t2 = th["values_from_train"]
    ecdf = th["sensitivity"]["train_ecdf_at_value"]
    below_t1 = max((float(k) for k in ecdf if float(k) < t1), default=None)
    sens_methods = th["sensitivity"]["by_quantile_method"]
    sens_same = len({tuple(v) for v in sens_methods.values()}) == 1
    rho = cf["spearman_margin_vs"]
    src = s["by_source"]
    src_by_margin = sorted(src, key=lambda k: src[k]["margin"]["mean"])
    chosen_share = sorted(mod["chosen_share_when_present"].items(), key=lambda kv: kv[1])
    dropped_rows = [r for r, n in c["dropped_by_reason"].items() if n]
    audit = s["structure_audit"]
    insp = s["inspection_checks"]
    L = []
    w = L.append

    w("# Exploratory Data Analysis: UltraFeedback preference margins\n")
    w(f"*Dataset:* `{s['provenance']['dataset_name']}` @ `{s['provenance']['dataset_revision'][:12]}` · "
      f"*Tokenizer:* `{s['provenance']['tokenizer_name']}` @ `{s['provenance']['tokenizer_revision'][:12]}`  ")
    w("*Generated by* `scripts/eda.py` from `results/eda/analysis_summary.json`. All numbers are computed from the "
      "downloaded data; none are estimates or recalled values.\n")
    w("> **Scope.** Every analysis in this report is **descriptive**. It characterises the training data; it does not "
      "show that margin (or any other variable) *causes* a difference in DPO outcomes. Causal claims require the "
      "controlled training experiments E1–E4.\n")

    w("## 1. Key observations\n")
    w(f"1. {c['raw']:,} raw pairs; {c['kept']:,} kept after cleaning ({_pct(c['overall_filter_rate'], 2)} dropped). "
      f"All raw pairs already have chosen-rating > rejected-rating.")
    w(f"2. Margins are discrete (steps of 0.25), right-skewed (mean {m_all['mean']:.2f}, median {m_all['median']:.2f}) "
      f"and concentrated at small values: margin 0.25 alone accounts for "
      f"{s['margin']['all_kept_value_counts']['0.25']:,} pairs ({_pct(s['margin']['all_kept_value_counts']['0.25'] / c['kept'])}).")
    chosen_means = ", ".join(f"{b} {bb[b]['chosen_rating_mean']:.2f}" for b in BUCKETS)
    bucket_fracs = ", ".join(f"{b} {_pct(th['bucket_fraction_train'][b])}" for b in BUCKETS)
    w(f"3. Margin is almost entirely determined by the **rejected** rating "
      f"(Spearman with rejected rating {_rho(rho['rejected_rating'])}; with chosen rating {_rho(rho['chosen_rating'])}). "
      f"Chosen responses are rated highly in every bucket (bucket means {chosen_means}).")
    w(f"4. Train-only tercile thresholds are t1 = {t1:g}, t2 = {t2:g}. Because margins are discrete, the buckets are "
      f"**not equal-sized**: {bucket_fracs} of train pairs.")
    w(f"5. Margin buckets differ in source mix (Cramér's V = {cf['bucket_vs_source']['cramers_v']:.3f}), "
      f"rejected-model identity (V = {cf['bucket_vs_rejected_model']['cramers_v']:.3f}) and response length "
      f"(mean rejected tokens {_trend([bb[b]['rejected_tokens_mean'] for b in BUCKETS])} from low to high bucket). "
      f"These are potential confounders for any margin effect.\n")

    w("## 2. Validation of schema and conversational structure\n")
    w(f"- Columns: {', '.join(f'`{k}`' for k in s['schema'])}. Schema matched the expected types.")
    w(f"- Rows: {audit['n_rows']:,}.")
    pats = "; ".join(f"`{k}`: {v:,}" for k, v in audit["turn_patterns"].items())
    w(f"- Turn patterns (chosen / rejected): {pats}.")
    w(f"- User turn identical to `prompt` in both chosen and rejected: {audit['user_turn_equals_prompt']:,} rows; "
      f"chosen and rejected share all non-final turns: {audit['chosen_rejected_same_user_turn']:,} rows.")
    w(f"- Byte-identical (after whitespace strip) chosen and rejected responses: {audit['identical_assistant_responses']:,} rows.")
    w(f"- Manual inspection of {insp['n']} seeded examples (one per source, then random; "
      f"[`reports/example_inspection.md`](example_inspection.md)): shared prompt {insp['shared_prompt']}/{insp['n']}, "
      f"distinct responses {insp['distinct_responses']}/{insp['n']}, prompt appears exactly once after TRL formatting "
      f"{insp['trl_prompt_once']}/{insp['n']}.")
    w("- Because the raw `chosen`/`rejected` lists repeat the user turn, `to_dpo_example` moves it to `prompt` and keeps "
      "only the assistant message in `chosen`/`rejected`, so the prompt is not duplicated in TRL inputs.\n")

    w("## 3. Cleaning\n")
    w("Rules are applied in the order below; each dropped row records the first rule it fails "
      "(`data/splits/dropped.csv`).\n")
    w("| Reason | Rows | Rate (of raw) | Sources |")
    w("|---|---:|---:|---|")
    for r, n in c["dropped_by_reason"].items():
        srcs = ", ".join(f"{k} {v}" for k, v in c["dropped_by_reason_and_source"].get(r, {}).items()) or "–"
        w(f"| `{r}` | {n:,} | {_pct(c['filter_rate_by_reason'][r], 3)} | {srcs} |")
    w(f"| **total** | **{c['dropped']:,}** | **{_pct(c['overall_filter_rate'], 3)}** | |\n")
    d = s["duplicates"]
    w(f"- *Duplicates:* {d['duplicate_groups']} normalized-prompt groups covering {d['rows_in_duplicate_groups']} rows; "
      f"{d['groups_differing_only_after_normalization']} of these groups differ in raw text and are only detected after "
      f"normalization (NFKC, lowercase, whitespace collapse). The lowest original index is kept; {d['rows_dropped']} rows dropped.")
    w(f"- *Overlong:* pairs whose full chat-templated sequence (incl. Qwen's default system prompt) exceeds "
      f"{s['provenance']['max_total_tokens']} tokens for either response are dropped, so training never truncates a response.")
    w("- *Identical responses* received different ratings despite identical text. For such a pair the DPO "
      "chosen/rejected log-ratio difference is always zero, so it contributes no gradient; they are dropped.")
    short = tl["pairs_with_response_le_2_tokens"]
    short_src = sorted(short["by_source"].items(), key=lambda kv: -kv[1])
    w(f"- Very short responses are **kept** because they are valid answers to label-style prompts: "
      f"{short['n']:,} kept pairs have a response of at most 2 tokens, of which "
      + ", ".join(f"{k} {v:,}" for k, v in short_src[:3])
      + ".\n")

    w("## 4. Leakage-safe splits\n")
    w(f"Kept pairs are assigned to splits by a salted SHA-256 of the normalized prompt (seed {s['provenance']['split_seed']}), "
      "so assignment is independent of row order and a prompt cannot appear in more than one split.\n")
    w("| Split | Pairs | Unique prompts | Fraction |")
    w("|---|---:|---:|---:|")
    for k in ("train", "validation", "test"):
        w(f"| {k} | {sp['pairs'][k]:,} | {sp['unique_prompts'][k]:,} | {_pct(sp['fraction'][k], 2)} |")
    w("")
    w(f"Prompt overlap between splits: {', '.join(f'{k} = {v}' for k, v in sp['prompt_overlap'].items())}. "
      "Manifest SHA-256 checksums are in `data/splits/SHA256SUMS`. "
      "Mean margin by split: " + ", ".join(f"{k} {s['margin']['by_split'][k]['mean']:.3f}" for k in sp["pairs"]) + ".\n")
    w(f"![Examples per source]({FIG}/fig5_examples_per_source.png)\n")
    w("*Figure 5. Kept pairs per source, stacked by split; labels give kept/raw counts.*\n")

    w("## 5. Ratings and margins\n")
    w(f"![Margin histogram]({FIG}/fig1_margin_histogram.png)\n")
    w(f"*Figure 1. Margin distribution of the {c['kept']:,} cleaned pairs.*\n")
    w(f"Chosen ratings: mean {ratings['chosen']['mean']:.2f}, median {ratings['chosen']['median']:.2f}, "
      f"IQR [{ratings['chosen']['p25']:.2f}, {ratings['chosen']['p75']:.2f}]. Rejected ratings: mean "
      f"{ratings['rejected']['mean']:.2f}, median {ratings['rejected']['median']:.2f}, IQR "
      f"[{ratings['rejected']['p25']:.2f}, {ratings['rejected']['p75']:.2f}]. The rejected rating is far more variable "
      f"(SD {ratings['rejected']['std']:.2f} vs {ratings['chosen']['std']:.2f}), which is why it drives the margin. "
      f"Chosen and rejected ratings are positively correlated "
      f"({_rho(ratings['spearman_chosen_vs_rejected'])}).\n")
    w(f"![Chosen vs rejected]({FIG}/fig2_chosen_vs_rejected.png)\n")
    w("*Figure 2. Chosen vs. rejected rating. All mass lies above the diagonal (positive margin); the densest cells "
      "are high chosen ratings paired with high rejected ratings, i.e. small margins.*\n")

    w("## 6. Margin by source\n")
    w(f"![Margin by source]({FIG}/fig3_margin_by_source.png)\n")
    w("*Figure 3. Margin by source, ordered by median.*\n")
    w("| Source | Kept | Mean margin | Median | Mean chosen / rejected rating | Mean tokens chosen / rejected | Train share low / med / high |")
    w("|---|---:|---:|---:|---|---|---|")
    for k in src_by_margin:
        v = src[k]
        bs = v["train_bucket_share"]
        w(f"| {k} | {v['n_kept']:,} | {v['margin']['mean']:.2f} | {v['margin']['median']:.2f} | "
          f"{v['chosen_rating_mean']:.2f} / {v['rejected_rating_mean']:.2f} | "
          f"{v['chosen_tokens_mean']:.0f} / {v['rejected_tokens_mean']:.0f} | "
          f"{_pct(bs['low'], 0)} / {_pct(bs['medium'], 0)} / {_pct(bs['high'], 0)} |")
    lo, hi = src_by_margin[0], src_by_margin[-1]
    w(f"\nThe lowest mean margin is in `{lo}` ({src[lo]['margin']['mean']:.2f}) and the highest in `{hi}` "
      f"({src[hi]['margin']['mean']:.2f}). Margin-based selection therefore implicitly re-weights sources: "
      f"`{hi}` makes up {_pct(bb['high']['source_share'].get(hi, 0))} of the high bucket vs "
      f"{_pct(bb['low']['source_share'].get(hi, 0))} of the low bucket, and `{lo}` makes up "
      f"{_pct(bb['high']['source_share'].get(lo, 0))} vs {_pct(bb['low']['source_share'].get(lo, 0))}.\n")

    w("## 7. Thresholds for margin buckets (train split only)\n")
    w(f"![Thresholds]({FIG}/fig6_margin_thresholds.png)\n")
    w("*Figure 6. Left: train margins coloured by bucket, dashed lines between buckets. Right: train ECDF; "
      "dotted lines mark the 1/3 and 2/3 levels.*\n")
    w(f"- Rule: {th['rule']}; thresholds are the {th['quantiles'][0]:.4f} and {th['quantiles'][1]:.4f} quantiles of the "
      f"train margins: t1 = {t1:g}, t2 = {t2:g}.")
    members = {b: ", ".join(f"{v:g}" for v in th["bucket_margin_values_train"][b]) for b in BUCKETS}
    w("- Bucket membership by margin value (train): " + "; ".join(f"{b}: {{{members[b]}}}" for b in BUCKETS) + ".")
    w("- Bucket sizes: " + "; ".join(
        f"{sname}: " + ", ".join(f"{b} {th['bucket_counts'][sname][b]:,}" for b in BUCKETS)
        for sname in ("train", "validation", "test")) + ".")
    if below_t1 is not None:
        w(f"- **Boundary sensitivity.** The train ECDF at margin {below_t1:g} is {ecdf[f'{below_t1:g}']:.4f}, "
          f"{'just below' if ecdf[f'{below_t1:g}'] < th['quantiles'][0] else 'above'} the 1/3 level "
          f"({th['quantiles'][0]:.4f}). Because all mass at a margin value sits in one bucket, the low bucket "
          f"contains {_pct(th['bucket_fraction_train']['low'])} of train pairs and the medium bucket only "
          f"{_pct(th['bucket_fraction_train']['medium'])}. A small change in the data could move t1 by one step.")
    w(f"- The thresholds are {'identical' if sens_same else 'different'} under numpy quantile methods "
      f"{', '.join(sens_methods)} ({'; '.join(f'{k}: {v}' for k, v in sens_methods.items())}).")
    w("- Equal-size training subsets are still possible because each condition samples a fixed number of pairs from "
      "its bucket, and every bucket is larger than the planned subset size.\n")

    w("## 8. Response length\n")
    w(f"![Length vs margin]({FIG}/fig4_length_diff_vs_margin.png)\n")
    w("*Figure 4. Chosen-minus-rejected response tokens per margin value (boxes: IQR, whiskers: 1.5 IQR; outliers hidden).*\n")
    w(f"- Response tokens: chosen median {tl['chosen_tokens']['median']:.0f} (mean {tl['chosen_tokens']['mean']:.0f}), "
      f"rejected median {tl['rejected_tokens']['median']:.0f} (mean {tl['rejected_tokens']['mean']:.0f}); "
      f"prompt (templated) median {tl['prompt_tokens']['median']:.0f}.")
    w(f"- The chosen response is longer in {_pct(tl['fraction_chosen_longer'])} of pairs "
      f"(equal length in {_pct(tl['fraction_equal_length'])}); median difference "
      f"{tl['token_length_diff']['median']:.0f} tokens. The fraction of pairs with a longer chosen response is "
      + ", ".join(f"{_pct(bb[b]['fraction_chosen_longer'])} ({b})" for b in BUCKETS)
      + " across train margin buckets, so this length asymmetry is present at every margin level.")
    w(f"- Train-split Spearman correlations with margin: length difference {_rho(rho['token_length_diff'])} "
      f"({_strength(rho['token_length_diff']['rho'])}); chosen tokens {_rho(rho['chosen_tokens'])} "
      f"({_strength(rho['chosen_tokens']['rho'])}); rejected tokens {_rho(rho['rejected_tokens'])} "
      f"({_strength(rho['rejected_tokens']['rho'])}); prompt tokens {_rho(rho['prompt_tokens'])} "
      f"({_strength(rho['prompt_tokens']['rho'])}). With n this large, p-values are tiny even for negligible effects; "
      "the effect sizes are what matter.\n")

    w("## 9. Model identity\n")
    w(f"![Model frequencies]({FIG}/fig7_model_frequencies.png)\n")
    w(f"*Figure 7. How often each of the {mod['n_models']} models produced the chosen (left) and rejected (right) response.*\n")
    top = ", ".join(f"`{k}` {_pct(v)}" for k, v in chosen_share[::-1][:3])
    bot = ", ".join(f"`{k}` {_pct(v)}" for k, v in chosen_share[:3])
    w(f"- Share of a model's appearances in which it is the chosen response — highest: {top}; lowest: {bot}.")
    w(f"- Pairs where both responses come from the same model: {mod['same_model_pairs']}.")
    w(f"- Bucket vs rejected model: Cramér's V = {cf['bucket_vs_rejected_model']['cramers_v']:.3f}; "
      f"bucket vs chosen model: V = {cf['bucket_vs_chosen_model']['cramers_v']:.3f}. Most common rejected models — "
      + "; ".join(f"{b}: {', '.join(list(bb[b]['top_rejected_models'])[:3])}" for b in BUCKETS) + ".")
    share = mod["chosen_share_when_present"]
    w("- Overall chosen-share of each bucket's three most common rejected models — "
      + "; ".join(f"{b}: " + ", ".join(f"{m} {_pct(share[m])}" for m in list(bb[b]["top_rejected_models"])[:3])
                  for b in BUCKETS)
      + ". Model identity therefore co-varies with margin bucket.\n")

    w("## 10. Potential confounders by margin bucket (train split)\n")
    w("| | " + " | ".join(BUCKETS) + " | trend low→high |")
    w("|---|" + "---:|" * len(BUCKETS) + "---|")
    rows = [("pairs", "n", "{:,}"), ("mean margin", "margin_mean", "{:.2f}"),
            ("mean chosen rating", "chosen_rating_mean", "{:.2f}"), ("mean rejected rating", "rejected_rating_mean", "{:.2f}"),
            ("mean prompt tokens", "prompt_tokens_mean", "{:.0f}"), ("mean chosen tokens", "chosen_tokens_mean", "{:.0f}"),
            ("mean rejected tokens", "rejected_tokens_mean", "{:.0f}"),
            ("mean length diff", "token_length_diff_mean", "{:.0f}"),
            ("median length diff", "token_length_diff_median", "{:.0f}"),
            ("chosen longer", "fraction_chosen_longer", "pct")]
    for label, key, fmt in rows:
        vals = [bb[b][key] for b in BUCKETS]
        cells = [_pct(v) if fmt == "pct" else fmt.format(v) for v in vals]
        w(f"| {label} | " + " | ".join(cells) + f" | {_trend(vals) if key != 'n' else ''} |")
    w(f"\nSource mix differs across buckets (χ² = {cf['bucket_vs_source']['chi2']:.0f}, dof = "
      f"{cf['bucket_vs_source']['dof']}, Cramér's V = {cf['bucket_vs_source']['cramers_v']:.3f}).\n")
    w("**Implications for the experiments (design, not results):**\n")
    w("- E2 (high) vs E4 (low) changes margin *together with* rejected-response quality, rejected-model identity, "
      "source mix and absolute response lengths. A performance difference between them cannot be attributed to "
      "margin alone.")
    w("- Possible controls to consider: source-stratified sampling within buckets, matching on response length, "
      "reporting per-source evaluation, or an additional condition that varies margin at fixed rejected-rating range.")
    w(f"- The unequal bucket sizes do not affect training budget (each condition uses the same subset size), but the "
      f"medium bucket offers the smallest candidate pool ({th['bucket_counts']['train']['medium']:,} train pairs).\n")

    w("## 11. What is descriptive and what is not\n")
    w("- **Descriptive (this report):** counts, filtering rates, distributions, correlations, and associations between "
      "margin and source/length/model. These describe the dataset only.")
    w("- **Not shown here:** whether training on any bucket improves a model, or why. Correlations between margin and "
      "length or source do not imply that either drives DPO outcomes.")
    w("- **Rating provenance:** per the dataset card, pairs were binarized using the *average of the preference "
      "ratings* (consistent with the observed 0.25 steps). UltraFeedback ratings come from GPT-4 annotation, so margin "
      "measures differences in an automatic judge's scores, not human preference strength.")
    w("- **p-values:** with tens of thousands of pairs almost any association is \"significant\"; we report effect "
      "sizes (Spearman ρ, Cramér's V) and avoid interpreting p-values as importance.\n")
    w("## Reproduction\n")
    w("```bash\npython scripts/prepare_data.py   # validation, cleaning, splits, checksums\n"
      "python scripts/eda.py            # summary JSON, figures, this report\n```")
    return "\n".join(L) + "\n"
